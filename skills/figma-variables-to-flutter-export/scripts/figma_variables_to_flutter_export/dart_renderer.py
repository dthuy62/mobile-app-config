class DartColorRenderer:
    def render(
        self,
        *,
        tokens: list[ColorToken],
        layer: str,
        class_prefix: str,
        base_class: str,
        base_import: str,
        light_mode: str,
        dark_mode: str,
        exclude_material_extension: bool,
    ) -> str:
        context = RenderContext(
            tokens=tokens,
            layer=layer,
            class_prefix=class_prefix,
            base_class=base_class,
            base_import=base_import,
            light_key=normalize_mode_name(light_mode),
            dark_key=normalize_mode_name(dark_mode),
            exclude_material_extension=exclude_material_extension,
        )
        return "\n".join(render_document(context))


class RenderContext:
    def __init__(
        self,
        *,
        tokens: list[ColorToken],
        layer: str,
        class_prefix: str,
        base_class: str,
        base_import: str,
        light_key: str,
        dark_key: str,
        exclude_material_extension: bool,
    ) -> None:
        self.tokens = tokens
        self.layer = layer
        self.class_prefix = class_prefix
        self.base_class = base_class
        self.base_import = base_import
        self.light_key = light_key
        self.dark_key = dark_key
        self.light_class = base_class if layer == "base" else class_name(class_prefix, "Colors")
        self.dark_class = class_name(class_prefix, "ColorsDark")
        self.theme_class = class_name(class_prefix, "ColorsTheme")
        self.accessor = f"{class_prefix[:1].lower()}{class_prefix[1:]}Colors" if class_prefix else "appColors"
        self.has_dark = any(dark_key in token.values_by_mode_name for token in tokens)
        self.extension_tokens = [
            token
            for token in tokens
            if layer == "system" and (not exclude_material_extension or token.field not in MATERIAL_COLOR_ROLES)
        ]


def render_document(context: RenderContext) -> list[str]:
    lines: list[str] = ["import 'package:flutter/material.dart';"]
    if context.layer == "system" and any(token.reference_field for token in context.tokens):
        lines.append(f"import '{context.base_import}';")
    lines.extend([
        "",
        "// Generated by figma-variables-to-flutter-export. Do not edit by hand.",
        "",
        "/// Static color constants.",
        f"abstract final class {context.light_class} {{",
    ])
    append_color_constants(lines, context.tokens, context.light_key, context=context)
    lines.extend(["}", ""])

    if context.layer == "system" and context.has_dark:
        lines.extend([
            "/// Static semantic color constants (dark theme defaults).",
            f"abstract final class {context.dark_class} {{",
        ])
        append_color_constants(lines, context.tokens, context.dark_key, context=context)
        lines.extend(["}", ""])

    if context.extension_tokens:
        append_theme_extension(lines, context)
    return lines


def append_theme_extension(lines: list[str], context: RenderContext) -> None:
    theme_class = context.theme_class
    lines.extend([
        "/// ThemeExtension for semantic color tokens.",
        f"class {theme_class} extends ThemeExtension<{theme_class}> {{",
        f"  const {theme_class}({{",
    ])
    append_color_fields(lines, context.extension_tokens, "    required this.{field},")
    lines.extend(["  });", ""])
    append_color_fields(lines, context.extension_tokens, "  final Color {field};")
    lines.extend(["", f"  static const light = {theme_class}("])
    append_color_fields(lines, context.extension_tokens, f"    {{field}}: {context.light_class}.{{field}},")
    lines.extend(["  );", ""])
    append_dark_theme_values(lines, context)
    lines.extend(["  @override", f"  {theme_class} copyWith({{"])
    append_color_fields(lines, context.extension_tokens, "    Color? {field},")
    lines.extend(["  }) =>", f"      {theme_class}("])
    append_color_fields(lines, context.extension_tokens, "        {field}: {field} ?? this.{field},")
    lines.extend(["      );", ""])
    lines.extend(["  @override", f"  {theme_class} lerp({theme_class}? other, double t) {{"])
    lines.extend(["    if (other == null) return this;", f"    return {theme_class}("])
    append_color_fields(lines, context.extension_tokens, "      {field}: Color.lerp({field}, other.{field}, t)!,")
    lines.extend(["    );", "  }", "}", ""])
    lines.extend([
        f"/// BuildContext accessor for [{theme_class}].",
        f"extension {theme_class}X on BuildContext {{",
        f"  {theme_class} get {context.accessor} =>",
        f"      Theme.of(this).extension<{theme_class}>() ?? {theme_class}.light;",
        "}",
        "",
    ])


def append_dark_theme_values(lines: list[str], context: RenderContext) -> None:
    lines.append(f"  static const dark = {context.theme_class}(")
    current_group: str | None = None
    for token in context.extension_tokens:
        if token.group != current_group:
            if current_group is not None:
                lines.append("")
            lines.append(f"    // {token.group}")
            current_group = token.group
        ref_class = context.dark_class if context.has_dark and context.dark_key in token.values_by_mode_name else context.light_class
        lines.append(f"    {token.field}: {ref_class}.{token.field},")
    lines.extend(["  );", ""])


def append_color_constants(
    lines: list[str],
    tokens: list[ColorToken],
    mode_key: str | None,
    *,
    context: RenderContext,
) -> None:
    current_group: str | None = None
    for token in tokens:
        value = color_value_expression(token, mode_key, context=context)
        if token.group != current_group:
            if current_group is not None:
                lines.append("")
            lines.append(f"  // {token.group}")
            current_group = token.group
        lines.append(f"  static const Color {token.field} = {value};")


def color_value_expression(token: ColorToken, mode_key: str | None, *, context: RenderContext) -> str:
    if context.layer == "system" and token.reference_field:
        return f"{context.base_class}.{token.reference_field}"
    value = (
        token.values_by_mode_name.get(mode_key)
        if mode_key is not None
        else next(iter(token.values_by_mode_name.values()))
    )
    return value or next(iter(token.values_by_mode_name.values()))


def append_color_fields(lines: list[str], tokens: list[ColorToken], declaration: str) -> None:
    current_group: str | None = None
    indent = declaration[: len(declaration) - len(declaration.lstrip())]
    for token in tokens:
        if token.group != current_group:
            if current_group is not None:
                lines.append("")
            lines.append(f"{indent}// {token.group}")
            current_group = token.group
        lines.append(declaration.format(field=token.field))


def class_name(prefix: str, suffix: str) -> str:
    clean = "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", prefix) if part)
    return f"{clean or 'App'}{suffix}"

