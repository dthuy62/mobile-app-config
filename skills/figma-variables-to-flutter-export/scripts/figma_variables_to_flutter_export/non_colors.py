from __future__ import annotations

import re
from dataclasses import replace
from typing import Any

from .colors import dart_field_name, normalize_mode_name, token_group_name
from .models import NonColorToken, Variable, Warn


TOKEN_TYPES = {
    "spacing": {"SPACING", "DIMENSION", "FLOAT", "NUMBER"},
    "radius": {"RADIUS", "RADII", "BORDERRADIUS", "BORDER_RADIUS", "DIMENSION", "FLOAT", "NUMBER"},
    "shadow": {"SHADOW", "BOXSHADOW", "BOX_SHADOW", "EFFECT"},
    "typography": {"TYPOGRAPHY", "TEXTSTYLE", "TEXT_STYLE"},
}

GENERIC_NUMBER_TYPES = {"DIMENSION", "FLOAT", "NUMBER"}
SPACING_SCOPES = {"GAP"}
RADIUS_SCOPES = {"CORNER_RADIUS"}
TYPOGRAPHY_PARTS = {
    "font-family": "fontFamily",
    "font-size": "fontSize",
    "font-weight": "fontWeight",
    "letter-spacing": "letterSpacing",
}

CLASS_SUFFIX = {
    "spacing": "Spacing",
    "radius": "Radius",
    "shadow": "Shadow",
    "typography": "Typography",
}

VALUE_TYPES = {
    "spacing": "double",
    "radius": "BorderRadius",
    "shadow": "List<BoxShadow>",
    "typography": "TextStyle",
}


class NonColorTokenBuilder:
    def build(self, variables: list[Variable], token_type: str, *, strict: bool, warn: Warn) -> list[NonColorToken]:
        field_sources: dict[str, list[str]] = {}
        tokens: list[NonColorToken] = []

        for var in variables + split_typography_variables(variables, token_type):
            if not matches_token_type(var, token_type):
                continue
            token = self._build_one(var, token_type)
            field_sources.setdefault(token.field, []).append(token.source_name)
            tokens.append(token)

        return validate_duplicate_fields(tokens, field_sources, strict=strict, warn=warn)

    def _build_one(self, var: Variable, token_type: str) -> NonColorToken:
        values: dict[str, str] = {}
        for mode_id, raw_value in var.values_by_mode.items():
            mode_name = normalize_mode_name(var.modes.get(str(mode_id), str(mode_id)))
            values[mode_name] = render_value(token_type, raw_value)

        return NonColorToken(
            field=non_color_field_name(var.name, token_type),
            group=token_group_name(var.name),
            source_name=var.name,
            values_by_mode_name=values,
        )


class DartNonColorRenderer:
    def render(self, *, tokens: list[NonColorToken], token_type: str, class_prefix: str, light_mode: str, dark_mode: str) -> str:
        context = NonColorRenderContext(
            tokens=tokens,
            token_type=token_type,
            class_prefix=class_prefix,
            light_key=normalize_mode_name(light_mode),
            dark_key=normalize_mode_name(dark_mode),
        )
        return "\n".join(render_document(context))


class NonColorRenderContext:
    def __init__(self, *, tokens: list[NonColorToken], token_type: str, class_prefix: str, light_key: str, dark_key: str) -> None:
        suffix = CLASS_SUFFIX[token_type]
        self.tokens = tokens
        self.token_type = token_type
        self.value_type = VALUE_TYPES[token_type]
        self.light_key = light_key
        self.dark_key = dark_key
        self.light_class = class_name(class_prefix, suffix)
        self.dark_class = class_name(class_prefix, f"{suffix}Dark")
        self.theme_class = class_name(class_prefix, f"{suffix}Theme")
        self.accessor = f"{class_prefix[:1].lower()}{class_prefix[1:]}{suffix}" if class_prefix else f"app{suffix}"
        self.has_dark = any(dark_key in token.values_by_mode_name for token in tokens)


def render_document(context: NonColorRenderContext) -> list[str]:
    lines = []
    if context.token_type == "spacing":
        lines.append("import 'dart:ui' show lerpDouble;")
    lines.extend([
        "import 'package:flutter/material.dart';",
        "",
        "// Generated by figma-variables-to-flutter-export. Do not edit by hand.",
        "",
        f"/// Static {context.token_type} tokens.",
        f"abstract final class {context.light_class} {{",
    ])
    append_constants(lines, context, context.light_key, context.light_class)
    lines.extend(["}", ""])

    if context.has_dark:
        lines.extend([
            f"/// Static {context.token_type} tokens (dark theme defaults).",
            f"abstract final class {context.dark_class} {{",
        ])
        append_constants(lines, context, context.dark_key, context.dark_class)
        lines.extend(["}", ""])

    append_theme_extension(lines, context)
    return lines


def append_constants(lines: list[str], context: NonColorRenderContext, mode_key: str, class_name_value: str) -> None:
    current_group: str | None = None
    for token in context.tokens:
        if token.group != current_group:
            if current_group is not None:
                lines.append("")
            lines.append(f"  // {token.group}")
            current_group = token.group
        value = token.values_by_mode_name.get(mode_key) or next(iter(token.values_by_mode_name.values()))
        lines.append(f"  static const {context.value_type} {token.field} = {value};")


def append_theme_extension(lines: list[str], context: NonColorRenderContext) -> None:
    theme_class = context.theme_class
    lines.extend([
        f"/// ThemeExtension for {context.token_type} tokens.",
        f"class {theme_class} extends ThemeExtension<{theme_class}> {{",
        f"  const {theme_class}({{",
    ])
    append_fields(lines, context, "    required this.{field},")
    lines.extend(["  });", ""])
    append_fields(lines, context, f"  final {context.value_type} {{field}};")
    lines.extend(["", f"  static const light = {theme_class}("])
    append_fields(lines, context, f"    {{field}}: {context.light_class}.{{field}},")
    lines.extend(["  );", ""])
    if context.has_dark:
        lines.extend([f"  static const dark = {theme_class}("])
        append_theme_values(lines, context)
        lines.extend(["  );", ""])
    lines.extend(["  @override", f"  {theme_class} copyWith({{"])
    append_fields(lines, context, f"    {context.value_type}? {{field}},")
    lines.extend([f"  }}) => {theme_class}("])
    append_fields(lines, context, "    {field}: {field} ?? this.{field},")
    lines.extend(["  );", ""])
    lines.extend(["  @override", f"  {theme_class} lerp({theme_class}? other, double t) {{"])
    lines.extend(["    if (other == null) return this;", f"    return {theme_class}("])
    append_lerp_fields(lines, context)
    lines.extend(["    );", "  }", "}", ""])
    lines.extend([
        f"/// BuildContext accessor for [{theme_class}].",
        f"extension {theme_class}X on BuildContext {{",
        f"  {theme_class} get {context.accessor} =>",
    ])
    fallback = f"      Theme.of(this).extension<{theme_class}>() ?? {theme_class}.light;"
    if len(fallback) <= 80:
        lines.append(fallback)
    else:
        lines.extend([
            f"      Theme.of(this).extension<{theme_class}>() ??",
            f"      {theme_class}.light;",
        ])
    lines.extend(["}", ""])


def append_theme_values(lines: list[str], context: NonColorRenderContext) -> None:
    current_group: str | None = None
    for token in context.tokens:
        if token.group != current_group:
            if current_group is not None:
                lines.append("")
            lines.append(f"    // {token.group}")
            current_group = token.group
        ref_class = context.dark_class if context.dark_key in token.values_by_mode_name else context.light_class
        lines.append(f"    {token.field}: {ref_class}.{token.field},")


def append_fields(lines: list[str], context: NonColorRenderContext, declaration: str) -> None:
    current_group: str | None = None
    indent = declaration[: len(declaration) - len(declaration.lstrip())]
    for token in context.tokens:
        if token.group != current_group:
            if current_group is not None:
                lines.append("")
            lines.append(f"{indent}// {token.group}")
            current_group = token.group
        lines.append(declaration.format(field=token.field))


def append_lerp_fields(lines: list[str], context: NonColorRenderContext) -> None:
    current_group: str | None = None
    for token in context.tokens:
        if token.group != current_group:
            if current_group is not None:
                lines.append("")
            lines.append(f"      // {token.group}")
            current_group = token.group
        if context.token_type == "spacing":
            value = f"lerpDouble({token.field}, other.{token.field}, t)!"
        elif context.token_type == "radius":
            value = f"BorderRadius.lerp({token.field}, other.{token.field}, t)!"
        elif context.token_type == "shadow":
            value = f"BoxShadow.lerpList({token.field}, other.{token.field}, t)!"
        else:
            value = f"TextStyle.lerp({token.field}, other.{token.field}, t)!"
        lines.append(f"      {token.field}: {value},")


def render_value(token_type: str, value: Any) -> str:
    if token_type == "spacing":
        return render_double(unwrap_value(value))
    if token_type == "radius":
        return f"BorderRadius.all(\n    Radius.circular({render_double(unwrap_value(value))}),\n  )"
    if token_type == "shadow":
        return render_shadow(unwrap_value(value))
    return render_text_style(unwrap_value(value))


def unwrap_value(value: Any) -> Any:
    if isinstance(value, dict) and "value" in value:
        return value["value"]
    return value


def render_double(value: Any) -> str:
    if isinstance(value, str):
        value = value.strip()
        if value.endswith("px"):
            value = value[:-2]
    number = float(value)
    return f"{number:g}.0" if number.is_integer() else f"{number:g}"


def render_shadow(value: Any) -> str:
    shadows = value if isinstance(value, list) else [value]
    return "const [\n    " + ",\n    ".join(render_box_shadow(shadow) for shadow in shadows) + ",\n  ]"


def render_box_shadow(value: Any) -> str:
    if not isinstance(value, dict):
        raise ValueError(f"Unsupported shadow value: {value!r}")
    color = render_color(value.get("color", "#000000"))
    x = render_double(value.get("x", value.get("offsetX", 0)))
    y = render_double(value.get("y", value.get("offsetY", 0)))
    blur = render_double(value.get("blur", value.get("blurRadius", 0)))
    spread = render_double(value.get("spread", value.get("spreadRadius", 0)))
    return (
        "BoxShadow("
        f"\n      color: {color},"
        f"\n      offset: Offset({x}, {y}),"
        f"\n      blurRadius: {blur},"
        f"\n      spreadRadius: {spread},"
        "\n    "
        ")"
    )


def render_text_style(value: Any) -> str:
    if not isinstance(value, dict):
        raise ValueError(f"Unsupported typography value: {value!r}")
    fields: list[str] = []
    field_map = {
        "fontFamily": "fontFamily",
        "fontSize": "fontSize",
        "letterSpacing": "letterSpacing",
    }
    for source, dart_name in field_map.items():
        if source in value:
            rendered = repr(str(value[source])) if source == "fontFamily" else render_double(value[source])
            fields.append(f"{dart_name}: {rendered}")
    line_height = value.get("height", value.get("lineHeight"))
    if line_height is not None:
        fields.append(f"height: {render_double(line_height)}")
    if "fontWeight" in value:
        fields.append(f"fontWeight: {render_font_weight(value['fontWeight'])}")
    if "fontStyle" in value:
        fields.append(f"fontStyle: {render_font_style(value['fontStyle'])}")
    if "color" in value:
        fields.append(f"color: {render_color(value['color'])}")
    return "TextStyle(\n    " + ",\n    ".join(fields) + ",\n  )"


def render_font_weight(value: Any) -> str:
    if isinstance(value, str):
        match = re.search(r"[1-9]00", value)
        if match:
            return f"FontWeight.w{match.group(0)}"
        names = {"normal": "w400", "regular": "w400", "medium": "w500", "semibold": "w600", "bold": "w700"}
        key = value.lower().replace(" ", "")
        if key in names:
            return f"FontWeight.{names[key]}"
    number = int(value)
    number = max(100, min(900, round(number / 100) * 100))
    return f"FontWeight.w{number}"


def render_font_style(value: Any) -> str:
    return "FontStyle.italic" if str(value).lower() == "italic" else "FontStyle.normal"


def render_color(value: Any) -> str:
    if isinstance(value, str):
        hex_value = value.strip().lstrip("#")
        if re.fullmatch(r"[0-9a-fA-F]{6}", hex_value):
            return f"Color(0xFF{hex_value.upper()})"
        if re.fullmatch(r"[0-9a-fA-F]{8}", hex_value):
            return f"Color(0x{hex_value[6:8].upper()}{hex_value[0:6].upper()})"
    raise ValueError(f"Unsupported color value: {value!r}")


def validate_duplicate_fields(
    tokens: list[NonColorToken],
    field_sources: dict[str, list[str]],
    *,
    strict: bool,
    warn: Warn,
) -> list[NonColorToken]:
    duplicate_messages = [f"{field}: {', '.join(sources)}" for field, sources in field_sources.items() if len(sources) > 1]
    if not duplicate_messages:
        return tokens

    message = "Duplicate Dart field names detected: " + "; ".join(duplicate_messages)
    if strict:
        raise ValueError(message)
    warn(message)
    counts: dict[str, int] = {}
    result: list[NonColorToken] = []
    for token in tokens:
        counts[token.field] = counts.get(token.field, 0) + 1
        field = token.field if counts[token.field] == 1 else f"{token.field}{counts[token.field]}"
        result.append(replace(token, field=field))
    return result


def canonical_type(value: str) -> str:
    return re.sub(r"[^A-Z0-9]+", "_", value.upper()).strip("_")


def matches_token_type(var: Variable, token_type: str) -> bool:
    resolved_type = canonical_type(var.resolved_type)
    if resolved_type not in TOKEN_TYPES[token_type]:
        return False
    if token_type not in {"spacing", "radius"} or resolved_type not in GENERIC_NUMBER_TYPES:
        return True
    return has_type_name(var.name, token_type) or has_type_scope(var.scopes, token_type)


def has_type_name(name: str, token_type: str) -> bool:
    normalized = re.sub(r"[^a-z0-9]+", "", name.split("/", 1)[0].lower())
    if token_type == "spacing":
        return normalized.startswith(("spacing", "gap", "padding", "margin"))
    return normalized.startswith(("radius", "radii", "borderradius", "cornerradius"))


def has_type_scope(scopes: tuple[str, ...], token_type: str) -> bool:
    normalized = {canonical_type(scope) for scope in scopes}
    return bool(normalized & (SPACING_SCOPES if token_type == "spacing" else RADIUS_SCOPES))


def non_color_field_name(name: str, token_type: str) -> str:
    if token_type == "spacing":
        name = re.sub(r"(?<=\d),(?=\d)", "p", name)
    return dart_field_name(name)


def split_typography_variables(variables: list[Variable], token_type: str) -> list[Variable]:
    if token_type != "typography":
        return []

    by_parent: dict[str, dict[str, Variable]] = {}
    for var in variables:
        parent, _, raw_part = var.name.rpartition("/")
        part = raw_part.lower()
        if parent and (part in TYPOGRAPHY_PARTS or part in {"font-weight-italic", "line-height"}):
            by_parent.setdefault(parent, {})[part] = var

    result: list[Variable] = []
    for parent, parts in by_parent.items():
        if "font-family" not in parts or "font-size" not in parts:
            continue
        value: dict[str, Any] = {}
        for part, key in TYPOGRAPHY_PARTS.items():
            if part in parts:
                value[key] = first_value(parts[part])
        if "font-weight-italic" in parts:
            value["fontStyle"] = "italic"
        if "line-height" in parts:
            font_size = parse_number(first_value(parts["font-size"]))
            value["height"] = parse_number(first_value(parts["line-height"])) / font_size
        result.append(
            Variable(
                id=parent,
                name=parent,
                resolved_type="TYPOGRAPHY",
                values_by_mode={"default": value},
                modes={"default": "default"},
            )
        )
    return result


def first_value(var: Variable) -> Any:
    return next(iter(var.values_by_mode.values()))


def parse_number(value: Any) -> float:
    value = unwrap_value(value)
    if isinstance(value, str) and value.strip().endswith("px"):
        value = value.strip()[:-2]
    return float(value)


def class_name(prefix: str, suffix: str) -> str:
    clean = "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", prefix) if part)
    return f"{clean or 'App'}{suffix}"
